"""Deterministic MZ font-alias runtime generator (contract v1).

``build_runtime(aliases, output_file)`` renders the JavaScript that the build
step appends to ``index.html`` after ``main.js``.  The module is pure standard
library and touches no filesystem, subprocess, network or font bytes: it only
validates the declared font families and the output basename, then renders both
into a fixed template.  See ``docs/rpg/FONT_ALIAS_CONTRACT.md``.
"""

from __future__ import annotations

import json
import re

__all__ = ['build_runtime']

_MAX_ALIASES = 16
_MAX_OUTPUT_FILE_LENGTH = 128
_FONT_SUFFIXES = ('.ttf', '.otf', '.woff', '.woff2')
_ALIAS_PATTERN = re.compile(r'[A-Za-z][A-Za-z0-9_-]{0,63}\Z')
#: characters that cannot appear in a plain basename handed to the game.
_UNSAFE_OUTPUT_CHARS = frozenset('/\\:"\'`*?<>|')
_CONFIG_PLACEHOLDER = '__AINIEE_CONFIG_JSON__'

_SCRIPT_TEMPLATE = r'''(function () {
    "use strict";

    /* Generated by ModuleFolders/Service/GameProject/FontAliasRuntime.py.
       Contract: docs/rpg/FONT_ALIAS_CONTRACT.md (schema_version 1). */

    var CONFIG = __AINIEE_CONFIG_JSON__;
    var SCHEMA = 1;
    var PREFIX = "AiNiee font alias override: ";
    var BRAND = typeof Symbol === "function" && Symbol.for
        ? Symbol.for("AiNieeFontAliasOverride.v1")
        : "__AiNieeFontAliasOverrideV1__";
    var ROOT = globalThis;
    var ALIASES = CONFIG.aliases;
    var OUTPUT_FILE = CONFIG.output_file;
    var CONFIG_ID = OUTPUT_FILE + "\n" + ALIASES.join("\n");

    var state = null;
    var doc = ROOT.document;
    var listening = false;

    function fail(message) {
        throw new Error(PREFIX + message);
    }

    function makeState() {
        var value = {
            schema_version: SCHEMA,
            aliases: ALIASES.slice(),
            output_file: OUTPUT_FILE,
            installed: false,
            error: null,
            loads: Object.create(null)
        };
        Object.defineProperty(value, BRAND, { value: CONFIG_ID });
        return value;
    }

    function ownsConfig(value) {
        return !!value && value[BRAND] === CONFIG_ID;
    }

    function sameConfig(value) {
        if (value.schema_version !== SCHEMA || value.output_file !== OUTPUT_FILE) {
            return false;
        }
        var names = value.aliases;
        if (!names || names.length !== ALIASES.length) {
            return false;
        }
        for (var index = 0; index < ALIASES.length; index++) {
            if (names[index] !== ALIASES[index]) {
                return false;
            }
        }
        return true;
    }

    function aliasIndex(family) {
        for (var index = 0; index < ALIASES.length; index++) {
            if (ALIASES[index] === family) {
                return index;
            }
        }
        return -1;
    }

    function makeWrapper(original, counts) {
        var wrapper = function (family) {
            if (aliasIndex(family) < 0) {
                return original.apply(this, arguments);
            }
            var args = Array.prototype.slice.call(arguments);
            args[1] = OUTPUT_FILE;
            counts[family] = (counts[family] || 0) + 1;
            return original.apply(this, args);
        };
        Object.defineProperty(wrapper, BRAND, { value: CONFIG_ID });
        return wrapper;
    }

    function busyFamily(manager) {
        var urls = manager._urls;
        if (!urls) {
            return null;
        }
        for (var index = 0; index < ALIASES.length; index++) {
            if (Object.prototype.hasOwnProperty.call(urls, ALIASES[index])) {
                return ALIASES[index];
            }
        }
        return null;
    }

    function install(strict) {
        var manager = ROOT.FontManager;
        if (!manager || typeof manager.load !== "function") {
            return false;
        }
        if (manager.load[BRAND] === CONFIG_ID) {
            state.installed = true;
            return true;
        }
        if (manager.load[BRAND] !== undefined) {
            fail("FontManager.load was already overridden by a different configuration.");
        }
        var busy = busyFamily(manager);
        if (busy) {
            state.installed = false;
            state.error = 'FontManager already started loading "' + busy + '"';
            if (strict) {
                fail('refusing to claim an override for the in-flight family "' + busy + '".');
            }
            return false;
        }
        manager.load = makeWrapper(manager.load, state.loads);
        state.installed = true;
        state.error = null;
        return true;
    }

    function addListeners() {
        if (listening || state.installed) {
            return;
        }
        listening = true;
        if (doc && typeof doc.addEventListener === "function") {
            doc.addEventListener("DOMContentLoaded", onDocumentLoad, true);
            doc.addEventListener("load", onDocumentLoad, true);
        }
        if (typeof ROOT.addEventListener === "function") {
            ROOT.addEventListener("load", onWindowLoad, true);
        }
        if (doc && doc.readyState === "complete") {
            onWindowLoad();
        }
    }

    function removeListeners() {
        if (!listening) {
            return;
        }
        listening = false;
        if (doc && typeof doc.removeEventListener === "function") {
            doc.removeEventListener("DOMContentLoaded", onDocumentLoad, true);
            doc.removeEventListener("load", onDocumentLoad, true);
        }
        if (typeof ROOT.removeEventListener === "function") {
            ROOT.removeEventListener("load", onWindowLoad, true);
        }
    }

    function onDocumentLoad() {
        if (install(false)) {
            removeListeners();
        } else if (state.error) {
            removeListeners();
        }
    }

    function onWindowLoad() {
        if (install(false)) {
            removeListeners();
            return;
        }
        removeListeners();
        if (!state.error) {
            state.error = "FontManager is not available; the alias override was not installed";
        }
    }

    var previous = ROOT.AiNieeFontAliasOverride;
    if (previous === undefined || previous === null) {
        state = makeState();
        ROOT.AiNieeFontAliasOverride = state;
        if (!install(true)) {
            addListeners();
        }
    } else {
        if (!previous[BRAND]) {
            fail("refusing to reuse an unverified AiNieeFontAliasOverride global object.");
        }
        state = previous;
        if (!ownsConfig(state) || !sameConfig(state)) {
            fail("refusing to change the live font mapping to a different configuration.");
        }
        if (!(state.installed && ownsConfig(ROOT.FontManager && ROOT.FontManager.load))) {
            install(false);
        }
    }
})();
'''


def _validated_aliases(aliases):
    """Return the declared families as a list, preserving the declared order."""

    if not isinstance(aliases, (list, tuple)):
        raise ValueError('FONT_ALIASES_INVALID: aliases must be a list or tuple')
    if not 1 <= len(aliases) <= _MAX_ALIASES:
        raise ValueError('FONT_ALIASES_INVALID: expected 1..%d font families' % _MAX_ALIASES)
    for name in aliases:
        if not isinstance(name, str) or not _ALIAS_PATTERN.match(name):
            raise ValueError('FONT_ALIASES_INVALID: %r is not a font-family name' % (name,))
    if len(set(aliases)) != len(aliases):
        raise ValueError('FONT_ALIASES_INVALID: font families must be unique')
    return list(aliases)


def _validated_output_file(output_file):
    """Return a validated plain basename for the copied replacement font."""

    if not isinstance(output_file, str) or not output_file:
        raise ValueError('FONT_ALIAS_OUTPUT_INVALID: output_file must be a non-empty string')
    if len(output_file) > _MAX_OUTPUT_FILE_LENGTH:
        raise ValueError(
            'FONT_ALIAS_OUTPUT_INVALID: output_file must not exceed %d characters'
            % _MAX_OUTPUT_FILE_LENGTH
        )
    if '..' in output_file:
        raise ValueError('FONT_ALIAS_OUTPUT_INVALID: output_file must not contain ".."')
    if not output_file.lower().endswith(_FONT_SUFFIXES):
        raise ValueError(
            'FONT_ALIAS_OUTPUT_INVALID: output_file must end with one of %s'
            % ', '.join(_FONT_SUFFIXES)
        )
    for char in output_file:
        if not 0x20 <= ord(char) <= 0x7E:
            raise ValueError(
                'FONT_ALIAS_OUTPUT_INVALID: output_file must be printable ASCII (found %r)' % char
            )
        if char in _UNSAFE_OUTPUT_CHARS:
            raise ValueError(
                'FONT_ALIAS_OUTPUT_INVALID: output_file must be a basename (found %r)' % char
            )
    return output_file


def build_runtime(aliases, output_file):
    """Render the font-alias runtime script as deterministic UTF-8 bytes.

    ``aliases`` is a list/tuple of 1..16 unique ASCII font-family identifiers.
    ``output_file`` is a plain ASCII basename with a .ttf/.otf/.woff/.woff2
    suffix that replaces only the ``filename`` argument of the intercepted
    ``FontManager.load`` calls.  Both are validated up front; every rejected
    input raises :class:`ValueError`.
    """

    names = _validated_aliases(aliases)
    target = _validated_output_file(output_file)
    config = {'schema_version': 1, 'aliases': names, 'output_file': target}
    script = _SCRIPT_TEMPLATE.replace(
        _CONFIG_PLACEHOLDER,
        json.dumps(config, ensure_ascii=True, separators=(',', ':')),
    )
    return script.encode('utf-8')
